def print(*args, **kwargs):
    """הדפסה בטוחה ב-Windows (מונע UnicodeEncodeError מאימוג'י בטרמינל)."""
    try:
        builtins.print(*args, **kwargs)
    except UnicodeEncodeError:
        sep = kwargs.get("sep", " ")
        end = kwargs.get("end", "\n")
        file_obj = kwargs.get("file", sys.stdout)
        flush = kwargs.get("flush", False)
        text = sep.join(str(a) for a in args)
        encoding = getattr(file_obj, "encoding", None) or "utf-8"
        safe_text = text.encode(encoding, errors="ignore").decode(encoding, errors="ignore")
        builtins.print(safe_text, end=end, file=file_obj, flush=flush)


def _create_http_session(impersonate=False):
    """יוצר Session עם כותרות דפדפן. impersonate=True משתמש ב-curl_cffi נגד CloudFront."""
    if impersonate:
        from curl_cffi import requests as cffi_requests
        session = cffi_requests.Session(impersonate="chrome")
    else:
        session = requests.Session()
    session.headers.update(REQUEST_HEADERS)
    return session


def _is_waf_error(exc):
    text = str(exc)
    text_l = text.lower()
    return "חסם את הבקשה" in text or "awswaf" in text_l or " 202" in text_l or " 403" in text_l


def _response_blocked(response):
    if response is None:
        return True
    if response.status_code in (403, 503):
        return True
    text = (response.text or "")[:2000].lower()
    if "request blocked" in text or "generated by cloudfront" in text or "awswaf" in text:
        return True
    if response.status_code == 202 and "insurance_date" not in text and "myform" not in text:
        return True
    return False


class InsuranceScraper:
    def __init__(self):
        self.driver = None
        self.session = None
        self._session_kind = None
        self.insurance_date = None
        self._session_lock = threading.Lock()

    def cleanup(self):
        try:
            if self.session is not None:
                self.session.close()
        except Exception:
            pass
        self.session = None

    def _clone_session(self):
        """Session נפרד ל-thread, עם אותם cookies."""
        impersonate = self._session_kind == "curl_cffi"
        cloned = _create_http_session(impersonate=impersonate)
        try:
            cloned.cookies.update(self.session.cookies)
        except Exception:
            for cookie in self.session.cookies:
                cloned.cookies.set(cookie.name, cookie.value, domain=getattr(cookie, "domain", None))
        return cloned

    def _apply_cookies(self, session, cookies):
        for cookie in cookies or []:
            domain = (cookie.get("domain") or "car.cma.gov.il").lstrip(".")
            try:
                session.cookies.set(cookie["name"], cookie["value"], domain=domain)
            except Exception:
                session.cookies.set(cookie["name"], cookie["value"])

    def _bootstrap_waf_cookies(self):
        """
        CloudFront/AWS WAF דורש הרצת JS בדפדפן.
        פותחים Chrome פעם אחת, לוקחים cookies, וסוגרים.
        """
        options = webdriver.ChromeOptions()
        options.add_argument("--no-sandbox")
        options.add_argument("--disable-dev-shm-usage")
        options.add_argument("--disable-gpu")
        options.add_argument("--window-size=900,700")
        driver = webdriver.Chrome(options=options)
        try:
            driver.get(config.MINISTRY_OF_TRANSPORT_URL)
            WebDriverWait(driver, 40).until(
                EC.presence_of_element_located((By.ID, "insurance_date"))
            )
            date = driver.find_element(By.ID, "insurance_date").get_attribute("value") or ""
            cookies = driver.get_cookies()
            print(f"WAF cookies נקלטו ({len(cookies)}), תאריך ביטוח: {date}")
            return date.strip(), cookies
        finally:
            try:
                driver.quit()
            except Exception:
                pass

    def _ensure_session(self, force=False):
        with self._session_lock:
            if not force and self.session is not None and self.insurance_date:
                return True

            if self.session is not None:
                try:
                    self.session.close()
                except Exception:
                    pass
                self.session = None

            try:
                insurance_date, cookies = self._bootstrap_waf_cookies()
            except Exception as e:
                print(f"ERROR: לא ניתן לפתוח דפדפן לאימות האתר: {e}")
                return False

            last_error = None
            for impersonate in (True, False):
                try:
                    session = _create_http_session(impersonate=impersonate)
                except ImportError:
                    last_error = "curl_cffi missing"
                    continue
                self._apply_cookies(session, cookies)
                self.session = session
                self._session_kind = "curl_cffi" if impersonate else "requests"
                self.insurance_date = insurance_date or self._parse_insurance_date("")
                print(f"HTTP session מוכן ({self._session_kind}), תאריך ביטוח: {self.insurance_date}")
                return True

            print(f"ERROR: לא ניתן לפתוח חיבור HTTP לאתר הביטוח: {last_error}")
            return False

    def _parse_insurance_date(self, html):
        try:
            soup = BeautifulSoup(html, "lxml")
            field = soup.find(id="insurance_date")
            value = (field.get("value") or "").strip() if field else ""
            if value:
                return value
        except Exception:
            pass
        next_month = (datetime.now().replace(day=1) + timedelta(days=32)).replace(day=1)
        return next_month.strftime("%d/%m/%Y")

    def _post_calculate(self, payload, session=None):
        http = session or self.session
        calculate_url = getattr(config, "CMA_CALCULATE_URL", "https://car.cma.gov.il/Parameters/Calculate")
        response = http.post(
            calculate_url,
            data=payload,
            timeout=REQUEST_TIMEOUT,
            headers={
                **REQUEST_HEADERS,
                "Content-Type": "application/x-www-form-urlencoded",
                "Referer": config.MINISTRY_OF_TRANSPORT_URL,
            },
        )
        if _response_blocked(response):
            raise RuntimeError(f"האתר חסם את הבקשה (HTTP {response.status_code})")
        response.raise_for_status()
        return response.text

    def _switch_sheet(self, sheet_id, session=None):
        """ASP.NET שומר את סוג הרכב ב-session; חייבים להחליף לפני Calculate."""
        http = session or self.session
        sheet_url = getattr(
            config,
            "CMA_SHEET_PARAMS_URL",
            "https://car.cma.gov.il/Parameters/GetParametersPerSheet",
        )
        response = http.post(f"{sheet_url}?sheet_id={sheet_id}", timeout=REQUEST_TIMEOUT)
        if _response_blocked(response):
            raise RuntimeError(f"האתר חסם החלפת סוג רכב (HTTP {response.status_code})")
        response.raise_for_status()
        return True

    def _extract_harel_price_from_html(self, html):
        soup = BeautifulSoup(html, "lxml")
        table = soup.find(id="ResultTable") or soup.find("table")
        rows = table.find_all("tr") if table else soup.find_all("tr")
        for row in rows:
            cells = row.find_all("td")
            if not cells:
                continue
            texts = [cell.get_text(" ", strip=True) for cell in cells]
            if not any("הראל" in text for text in texts):
                continue
            for text in texts:
                if "הראל" in text:
                    continue
                price = self._parse_numeric_value(text)
                if price is not None and price >= PRICE_MIN:
                    return price
            prices = [
                self._parse_numeric_value(text)
                for text in texts
                if self._parse_numeric_value(text) is not None
                and self._parse_numeric_value(text) >= PRICE_MIN
            ]
            if prices:
                return max(prices)
        return None

    @staticmethod
    def _parse_numeric_value(raw_text):
        if not raw_text:
            return None
        cleaned = raw_text.replace("₪", "").replace(" ", "")
        match = re.search(r"\d[\d,]*(?:\.\d+)?", cleaned)
        if not match:
            return None
        try:
            return float(match.group(0).replace(",", ""))
        except ValueError:
            return None

