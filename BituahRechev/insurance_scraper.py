    def _scrape_kind(self, kind):
        if not self._ensure_session():
            return {}
        jobs = [job for job in self._all_jobs() if job["kind"] == kind]
        data = self._run_jobs(jobs)
        if kind == "private":
            return data.get("private_car") or {}
        if kind == "commercial":
            return data.get("commercial_car") or {}
        return data.get("special_vehicle") or {}

