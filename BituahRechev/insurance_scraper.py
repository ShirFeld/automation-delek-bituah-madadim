    def _empty_insurance_data(self):
        return {"private_car": {}, "commercial_car": {}, "special_vehicle": {}}

    def _store_job_price(self, insurance_data, job, price):
        if job["kind"] == "private":
            insurance_data["private_car"].setdefault(job["group"], {})[job["col"]] = price
        elif job["kind"] == "commercial":
            insurance_data["commercial_car"].setdefault(job["group"], {})[job["col"]] = price
        else:
            insurance_data["special_vehicle"][job["key"]] = price

    def _job_has_price(self, insurance_data, job):
        if job["kind"] == "private":
            return bool(insurance_data["private_car"].get(job["group"], {}).get(job["col"]))
        if job["kind"] == "commercial":
            return bool(insurance_data["commercial_car"].get(job["group"], {}).get(job["col"]))
        return bool(insurance_data["special_vehicle"].get(job["key"]))

    def _run_jobs(self, jobs, display_callback=None):
        insurance_data = self._empty_insurance_data()
        if not jobs:
            return insurance_data

        sheet_ids = {"private": 1, "commercial": 5, "special": 7}
        for kind in ("private", "commercial", "special"):
            kind_jobs = [job for job in jobs if job["kind"] == kind]
            if not kind_jobs:
                continue
            self._switch_sheet(sheet_ids[kind])
            if display_callback:
                display_callback(f"שולף {kind}: {len(kind_jobs)} תרחישים")
            for completed, job in enumerate(kind_jobs, 1):
                price = self._quote_harel(job["payload"], session=self.session)
                self._store_job_price(insurance_data, job, price)
                if price is not None:
                    print(f"OK {job['label']}: {price}")
                else:
                    print(f"FAIL {job['label']}")
                if display_callback:
                    status = f"{price} ₪" if price is not None else "נכשל"
                    display_callback(f"{completed}/{len(kind_jobs)} {job['label']}: {status}")
        return insurance_data

    def _merge_insurance_data(self, target, incoming):
        for group, cols in (incoming.get("private_car") or {}).items():
            target["private_car"].setdefault(group, {})
            for col, price in (cols or {}).items():
                if price is not None:
                    target["private_car"][group][col] = price
        for group, cols in (incoming.get("commercial_car") or {}).items():
            target["commercial_car"].setdefault(group, {})
            for col, price in (cols or {}).items():
                if price is not None:
                    target["commercial_car"][group][col] = price
        for key, price in (incoming.get("special_vehicle") or {}).items():
            if price is not None:
                target["special_vehicle"][key] = price
        return target

    def _retry_missing_insurance_scenarios(self, insurance_data, display_callback=None, max_rounds=2):
        jobs = self._all_jobs()
        for round_num in range(1, max_rounds + 1):
            missing = [job for job in jobs if not self._job_has_price(insurance_data, job)]
            if not missing:
                break
            msg = f"ניסיון חוזר {round_num}/{max_rounds} - חסרים {len(missing)} מחירים..."
            print(msg)
            if display_callback:
                display_callback(msg)
            retry_data = self._run_jobs(missing, display_callback=display_callback)
            self._merge_insurance_data(insurance_data, retry_data)
        return insurance_data

