    def _quote_harel(self, payload, session=None, attempts=2):
        last_error = None
        http = session
        for attempt in range(1, attempts + 1):
            try:
                if http is None:
                    http = self._clone_session()
                html = self._post_calculate(payload, session=http)
                price = self._extract_harel_price_from_html(html)
                if price is not None:
                    return price
                last_error = "לא נמצא מחיר הראל"
            except Exception as e:
                last_error = e
                http = None
                if _is_waf_error(e):
                    print("WAF פג, מרענן cookies...")
                    if self._ensure_session(force=True):
                        sheet_id = payload.get("sheet_id")
                        if sheet_id:
                            try:
                                self._switch_sheet(sheet_id)
                            except Exception as switch_error:
                                print(f"WARNING: החלפת סוג רכב אחרי רענון נכשלה: {switch_error}")
                        http = self.session
                        continue
            if attempt < attempts:
                print(f"ניסיון {attempt}/{attempts} נכשל ({last_error}), מנסה שוב...")
        print(f"ERROR: לא נמצא מחיר הראל: {last_error}")
        return None

